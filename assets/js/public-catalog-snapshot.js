export function canShowPublicSnapshot(error){
 if(error?.name==="AbortError")return false;
 const status=Number(error?.status??0);
 return [0,400,404,408,429,500,502,503,504].includes(status);
}
export function snapshotCategories(){
 const categories=new Map();
 for(const p of publicCatalogSnapshot)
  for(const c of p.categories||[])categories.set(c.id,c);
 return [...categories.values()].sort((a,b)=>a.name.localeCompare(b.name,"pt-BR"));
}
export function snapshotProduct(id){
 const product=publicCatalogSnapshot.find(p=>p.id===Number(id));
 return product?{...product,offlineSnapshot:true}:null;
}
export function snapshotCatalogPage(page=0,filters={}){
 const index=Number(page);
 if(!Number.isSafeInteger(index)||index<0)throw new RangeError("Página inválida.");
 const q=String(filters.q??"").trim().toLocaleLowerCase("pt-BR");
 const category=Number(filters.categoryId??0);
 const filtered=publicCatalogSnapshot.filter(p=>{
  if(q&&!((p.name+" "+p.description).toLocaleLowerCase("pt-BR").includes(q)))return false;
  if(category>0&&!p.categories.some(c=>c.id===category))return false;
  return true;
 });
 // Prices are NOT present in the snapshot. Never pretend to sort or filter by price.
 if(filters.sort==="name")filtered.sort((a,b)=>a.name.localeCompare(b.name,"pt-BR"));
 const size=12,offset=index*size;
 return {items:filtered.slice(offset,offset+size).map(p=>({...p,offlineSnapshot:true})),
  hasNext:offset+size<filtered.length,offlineSnapshot:true,total:filtered.length,
  priceFilterUnavailable:filters.maxPrice!==null&&filters.maxPrice!==undefined&&filters.maxPrice!==""};
}
